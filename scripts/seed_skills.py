def _derive_summary(desc, body):
    """从正文「适用场景」首条推出路由摘要。

    为什么必须显式写 ``summary``：``sfx`` 的解析器在缺少该字段时会退化成
    ``description[:40] + " 元数据待补全"``，这个标记会原样进入 agent.md 的
    路由表 —— 33 个技能就是 33 处噪音。摘要列是 LLM 选技能时唯一看的文本，
    所以它应该回答"什么时候用我"，而不是重复"我是谁"。
    """
    marker = "## 适用场景\n\n- "
    idx = body.find(marker)
    if idx >= 0:
        start = idx + len(marker)
        end = body.find("\n", start)
        first = body[start:end].strip()
        if first:
            return f"{desc}；适用：{first}"[:60]
    return desc[:60]


def _fm(name, display, desc, tags, summary="", author="skillforge"):
    tag_line = ", ".join(tags)
    return (
        "---\n"
        f"name: {name}\n"
        f"display_name: {display}\n"
        f"description: {desc}\n"
        f"summary: {summary or desc}\n"
        f"tags: {tag_line}\n"
        "version: 1.0.0\n"
        f"author: {author}\n"
        "license: MIT\n"
        "---\n"
    )


def _body(title, goal, scenes, steps, checklist, deliver):
    out = [f"# {title}", "", "## 目标", "", goal, "", "## 适用场景", ""]
    out += [f"- {s}" for s in scenes]
    out += ["", "## 工作流", ""]
    for i, s in enumerate(steps, 1):
        out.append(f"{i}. {s}")
    out += ["", "## 检查清单", ""]
    out += [f"- [ ] {c}" for c in checklist]
    out += ["", "## 产出要求", "", deliver, ""]
    return "\n".join(out)


