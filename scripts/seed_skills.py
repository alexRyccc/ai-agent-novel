def main() -> int:
    target = sys.argv[1] if len(sys.argv) > 1 else ROOT
    target = os.path.expanduser(target)
    created = 0
    for name, display, desc, tags, body in SKILLS:
        directory = os.path.join(target, name)
        os.makedirs(directory, exist_ok=True)
        path = os.path.join(directory, "SKILL.md")
        summary = _derive_summary(desc, body)
        # 分类标签 + 召回说法，去重但保持顺序（分类在前，便于人读）
        merged = list(tags)
        for extra in EXTRA_TAGS.get(name, ()):
            if extra not in merged:
                merged.append(extra)
        content = _fm(name, display, desc, merged, summary) + "\n" + body
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        created += 1
    print(f"已生成 {created} 个 skill -> {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
